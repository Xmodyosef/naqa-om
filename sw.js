/* Naqa SW — network-first for admin; shell cache 20261125pc3 */
const CACHE = "naqa-shell-20261125pills1";
const PRECACHE = ["./", "./index.html", "./manifest.webmanifest", "./logo.svg"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET") return;
  // Always network for admin panel + its CSS/JS
  if (url.pathname.includes("admin") || url.pathname.includes("/js/") || url.pathname.includes("/css/")) {
    e.respondWith(
      fetch(e.request).then((res) => res).catch(() => caches.match(e.request))
    );
    return;
  }
  e.respondWith(
    caches.match(e.request).then((hit) => hit || fetch(e.request).then((res) => {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(e.request, copy));
      return res;
    }).catch(() => caches.match("./index.html")))
  );
});
